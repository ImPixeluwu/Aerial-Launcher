/**
 * Compact record generated by scripts/generate-stw-data.mjs.
 */
type StwItemRecord = {
  n: string
  r?: string
  t?: number
  k: 'melee' | 'ranged' | 'trap' | 'ingredient' | 'material'
  s?: string
  d?: number
  i?: string
  l?: string
  b?: InventoryItemBaseStats
  x?: StwStatScaling
}

/**
 * value * (1 + (level - baseLevel) * scale) for the stats that scale
 */
type StwStatScaling = {
  baseLevel: number
  damage?: number
  impact?: number
}

type StwAlterationRecord = {
  n: string
  r?: string
  m?: Array<InventoryStatModifier>
}

type StwRatingTier = {
  FirstLevel: number
  Ratings: Array<number>
}

const items = itemsJson.items as unknown as Record<string, StwItemRecord>
const descriptions = itemsJson.descriptions as Array<string>
const alterations = alterationsJson as unknown as Record<
  string,
  StwAlterationRecord
>
const itemRatings = itemRatingsJson as Record<string, StwRatingTier>
const legacyAlterations = legacyAlterationsJson as Record<string, Array<string>>
const schematicExceptions = schematicsJson as Record<string, string>

const rarityCodes = new Set<string>(Object.values(RarityType))

// Perk tiers map to the in-game colors: grey, green, blue, purple, gold
const perkTierRarities = [
  RarityType.Common,
  RarityType.Uncommon,
  RarityType.Rare,
  RarityType.Epic,
  RarityType.Legendary,
]

const elements: Array<InventoryElement> = [
  'Energy',
  'Fire',
  'Nature',
  'Physical',
  'Water',
]

const filterTypeBySubType: Record<string, InventoryFilterType> = {
  assault: 'assault',
  pistol: 'pistol',
  shotgun: 'shotgun',
  sniper: 'sniper',
  smg: 'smg',
  explosive: 'explosive',
  sword: 'melee_sword',
  axe: 'melee_axe',
  scythe: 'melee_scythe',
  spear: 'melee_spear',
  hardware: 'melee_hammer',
  club: 'melee_bat',
}

function toRarity(code?: string) {
  return code && rarityCodes.has(code) ? (code as RarityType) : null
}

function imageUrl(file?: string) {
  return file ? `${sourceJson.imageBaseUrl}${encodeURIComponent(file)}` : null
}

export function findStwItem(templateId: string) {
  const record = items[templateId.toLowerCase()]

  if (!record) {
    return null
  }

  return {
    name: record.n,
    description: record.d !== undefined ? descriptions[record.d] ?? null : null,
    rarity: toRarity(record.r),
    tier: record.t ?? null,
    kind: record.k,
    subType: record.s ?? null,
    filterType: record.s
      ? filterTypeBySubType[record.s.toLowerCase()] ?? null
      : null,
    imageUrl: imageUrl(record.i),
    baseStats: record.b ?? null,
    scaling: record.x ?? null,
  }
}

/**
 * Template id of the weapon or trap a schematic crafts, in lower case:
 * "Schematic:sid_X" -> "weapon:wid_X" or "trap:tid_X", except for the few
 * schematics listed in the game data with a different result. Null when
 * the item is not in the game data.
 */
export function resolveStwSchematic(templateId: string) {
  const schematicId = templateId.toLowerCase()
  const id = schematicId.replace(/^schematic:/, '').replace(/^sid_/, '')

  return (
    schematicExceptions[schematicId] ??
    [`weapon:wid_${id}`, `trap:tid_${id}`].find(
      (candidate) => items[candidate],
    ) ??
    null
  )
}

function findAlterationRecord(id: string) {
  return alterations[`alteration:${id.toLowerCase()}`]
}

function parseAlterationTier(id: string) {
  const tierMatch = id.match(/_t0?([1-9])$/i)

  return tierMatch ? Math.min(Number(tierMatch[1]), 5) : null
}

function joinSentences(parts: Array<string>) {
  return parts
    .map((part, index) =>
      index < parts.length - 1 && !/[.!?]$/.test(part) ? `${part}.` : part,
    )
    .join(' ')
}

function humanizeAlterationId(id: string) {
  const words = id
    .toLowerCase()
    .replace(/^aid_(?:att_|g_|conditional_)?/, '')
    .replace(/_alt\d$/, '')
    .split('_')
    .filter(Boolean)
  const text = words.join(' ')

  return text.charAt(0).toUpperCase() + text.slice(1)
}

/**
 * Legacy weapons keep perk ids from the old perk system, which are no
 * longer in the game data: "aid_att_ranged_damage", "..._alt1", ...
 * The game's MigrationMapping table maps each one to a current perk, and
 * sometimes an additional one (element + affliction perks).
 */
function resolveMigratedAlteration(id: string) {
  const targets = legacyAlterations[`alteration:${id.toLowerCase()}`]

  if (!targets) {
    return null
  }

  const records = targets.map((target) => alterations[target])
  const mainId = targets[0].replace(/^alteration:/, '')

  return {
    name: joinSentences(records.map((record) => record.n)),
    tier: parseAlterationTier(mainId),
    rarity: records[0].r,
    modifiers: records.flatMap((record) => record.m ?? []),
  }
}

/**
 * Fallback for legacy ids missing from MigrationMapping: the base id is
 * tier 1 and "_altN" is tier N + 1, with the same values as the current
 * "aid_att_<stat>_t0X" perks.
 */
function resolveLegacyAlteration(id: string) {
  const migrated = resolveMigratedAlteration(id)

  if (migrated) {
    return migrated
  }

  const elementAffliction = id.match(
    /^aid_g_(?:ranged|melee)_(energy|fire|nature|physical|water)affliction$/i,
  )

  if (elementAffliction) {
    const element = elements.find(
      (value) => value.toLowerCase() === elementAffliction[1].toLowerCase(),
    )

    return {
      name: `Element: ${element} and 10% Weapon Damage. Causes Affliction damage for 6 seconds.`,
      tier: null,
      rarity: undefined,
      modifiers: [],
    }
  }

  const attribute = id.match(
    /^aid_att_(?:(ranged|melee|trap)_)?([a-z]+)(?:_alt(\d))?$/i,
  )

  if (!attribute) {
    return null
  }

  const [, scope, stat, alt] = attribute
  const tier = Math.min(alt ? Number(alt) + 1 : 1, 5)
  const candidates = [
    `aid_att_${stat}_t0${tier}`,
    scope ? `aid_att_${stat}_${scope}_t0${tier}` : null,
  ]
  const record = candidates
    .map((candidate) => (candidate ? findAlterationRecord(candidate) : null))
    .find(Boolean)

  return {
    name: record?.n ?? humanizeAlterationId(id),
    tier,
    rarity: record?.r,
    modifiers: record?.m ?? [],
  }
}

export function findStwAlteration(alterationId: string): InventoryAlteration {
  const id = alterationId.replace(/^alteration:/i, '')
  const record = findAlterationRecord(id)
  const legacy = record ? null : resolveLegacyAlteration(id)
  const tier = legacy ? legacy.tier : parseAlterationTier(id)
  const name = record?.n ?? legacy?.name ?? humanizeAlterationId(id)
  const elementName = name.match(/^Element: (\w+)/)?.[1]

  return {
    id,
    name,
    tier,
    rarity: tier
      ? perkTierRarities[tier - 1]
      : toRarity(record?.r ?? legacy?.rarity),
    element:
      elements.find((element) => element === elementName) ??
      (/_ele_|_ele$/i.test(id)
        ? elements.find((element) =>
            id.toLowerCase().includes(element.toLowerCase()),
          ) ?? null
        : null),
    legacy: !record,
    modifiers: record?.m ?? legacy?.modifiers ?? [],
  }
}

/**
 * Item stats at its level with its perks applied. Level scaling and perk
 * values come from the game data; perks on the same stat add up
 * (+10% and +15% = +25%). Damage leaves out the player's F.O.R.T. bonus.
 */
export function calculateStwStats({
  alterations: itemAlterations,
  baseStats,
  level,
  scaling,
}: {
  alterations: Array<InventoryAlteration>
  baseStats: InventoryItemBaseStats | null
  level: number | null
  scaling: StwStatScaling | null
}): InventoryItemStats | null {
  if (!baseStats) {
    return null
  }

  const modifiers = itemAlterations.flatMap(
    (alteration) => alteration.modifiers,
  )
  const multiplier = (attribute: string) =>
    1 +
    modifiers
      .filter(([name, mode]) => name === attribute && mode === 'm')
      .reduce((total, [, , value]) => total + (value - 1), 0)
  const additive = (attribute: string) =>
    modifiers
      .filter(([name, mode]) => name === attribute && mode === 'a')
      .reduce((total, [, , value]) => total + value, 0)
  const levelFactor = (scale?: number) =>
    scale && level !== null
      ? 1 + (level - (scaling?.baseLevel ?? 1)) * scale
      : 1
  const scale = (value: number | undefined, factor: number) =>
    value === undefined ? undefined : value * factor

  const fireRateMultiplier = multiplier('WeaponRateOfFire')
  // Approximation: the game converts Critical Rating with a curve that is
  // not in the game data, so each rating point is summed as 1% crit chance
  const critRating = additive('CritRating')
  const stats: InventoryItemStats = {
    ...baseStats,
    critChance:
      baseStats.critChance === undefined
        ? undefined
        : baseStats.critChance + critRating / 100,
    damage: scale(
      baseStats.damage,
      levelFactor(scaling?.damage) * multiplier('OutgoingAbilityDamage'),
    ),
    impact: scale(
      baseStats.impact,
      levelFactor(scaling?.impact) * multiplier('OutgoingBaseImpactDamage'),
    ),
    critDamage:
      baseStats.critDamage === undefined
        ? undefined
        : baseStats.critDamage + additive('DiceCritMultiplier'),
    fireRate: scale(baseStats.fireRate, fireRateMultiplier),
    attackTime: scale(baseStats.attackTime, 1 / fireRateMultiplier),
    clipSize:
      baseStats.clipSize === undefined
        ? undefined
        : Math.round(baseStats.clipSize * multiplier('WeaponAmmoClipSize')),
    reloadTime: scale(
      baseStats.reloadTime,
      1 / multiplier('WeaponReloadSpeed'),
    ),
    durability:
      baseStats.durability === undefined
        ? undefined
        : Math.round(
            baseStats.durability *
              multiplier('CharacterItemDurabilityDecayModifier'),
          ),
  }

  return Object.fromEntries(
    Object.entries(stats).filter(([, value]) => value !== undefined),
  ) as InventoryItemStats
}

/**
 * Maximum level for a tier, including upgrades past the regular cap
 * (attributes.max_level_bonus).
 */
export function stwMaxLevel(tier: number, maxLevelBonus = 0) {
  return tier * 10 + maxLevelBonus
}

/**
 * Each supercharge raises the level cap by 2, from 50 up to 60.
 */
export function stwSuperchargeLevel(level: number | null) {
  return level !== null && level > 50
    ? Math.min(Math.floor((level - 50) / 2), 5)
    : 0
}

/**
 * Levels past the tier cap. Supercharged items go past level 50; if the
 * profile does not say so with max_level_bonus, trust the item level
 * instead of capping it.
 */
export function stwLevelBonus({
  level,
  maxLevelBonus = 0,
  tier,
}: {
  level: number | null
  maxLevelBonus?: number
  tier: number | null
}) {
  return tier && level !== null
    ? Math.max(maxLevelBonus, level - stwMaxLevel(tier))
    : maxLevelBonus
}

/**
 * Item power level (PL) from the game's item rating table, keyed by
 * rarity and tier, indexed by level.
 */
export function calculateStwPowerLevel({
  level,
  maxLevelBonus = 0,
  rarity,
  tier,
}: {
  level: number | null
  maxLevelBonus?: number
  rarity: RarityType | null
  tier: number | null
}) {
  if (!rarity || !tier || level === null) {
    return null
  }

  const ratingTier = itemRatings[`${rarity.toUpperCase()}_T0${tier}`]

  if (!ratingTier) {
    return null
  }

  const cappedLevel = Math.min(level, stwMaxLevel(tier, maxLevelBonus))
  const index = cappedLevel - ratingTier.FirstLevel

  if (index < 0) {
    return null
  }

  const ratings = ratingTier.Ratings

  return Math.floor(ratings[Math.min(index, ratings.length - 1)])
}
